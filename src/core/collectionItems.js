function slugify(text) {
  return String(text)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

const ITEMS = CATALOG_RAW.map(([category, rarity, emoji, name]) => ({
  id: `${category}:${slugify(name)}`,
  category,
  rarity,
  emoji,
  name,
}));

const ITEMS_BY_ID = new Map(ITEMS.map(item => [item.id, item]));
const ITEMS_BY_RARITY = {};
for (const rarity of Object.keys(RARITIES)) {
  ITEMS_BY_RARITY[rarity] = ITEMS.filter(item => item.rarity === rarity);
}

function getItem(id) {
  return ITEMS_BY_ID.get(id) || null;
}

function getRarity(id) {
  return RARITIES[id] || RARITIES.commun;
}

// Tirage : on choisit d'abord une rareté (pondérée), puis un objet au hasard dans cette rareté.
function rollItem() {
  const rarities = Object.values(RARITIES).filter(r => ITEMS_BY_RARITY[r.id].length > 0);
  const total = rarities.reduce((sum, r) => sum + r.weight, 0);
  let roll = Math.random() * total;
  let picked = rarities[rarities.length - 1];
  for (const rarity of rarities) {
    roll -= rarity.weight;
    if (roll <= 0) { picked = rarity; break; }
  }
  const pool = ITEMS_BY_RARITY[picked.id];
  return pool[Math.floor(Math.random() * pool.length)];
}

// Valeur de rachat boutique (ratio configurable par serveur)
function getSellValue(item, ratio) {
  return Math.max(1, Math.floor(getRarity(item.rarity).value * ratio));
}

// Gain moyen de rachat d'un tirage (sert à prévenir l'admin si la roue devient rentable)
function expectedSellValue(ratio) {
  const rarities = Object.values(RARITIES).filter(r => ITEMS_BY_RARITY[r.id].length > 0);
  const total = rarities.reduce((sum, r) => sum + r.weight, 0);
  return rarities.reduce((sum, r) => sum + (r.weight / total) * Math.max(1, Math.floor(r.value * ratio)), 0);
}

function formatItem(item, { withRarity = false } = {}) {
  const base = `${item.emoji} **${item.name}**`;
  if (!withRarity) return base;
  return `${base} ${getRarity(item.rarity).emoji} ${getRarity(item.rarity).label}`;
}

